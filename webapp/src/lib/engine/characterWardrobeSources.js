function freezeTree(value) {
  if (value && typeof value === 'object') { Object.values(value).forEach(freezeTree); Object.freeze(value); }
  return value;
}
export const CHARACTER_WARDROBE_SOURCES = freezeTree(sources);
function sourceFor(id) {
  if (!Object.hasOwn(CHARACTER_WARDROBE_SOURCES, id)) throw new Error('Unknown character wardrobe source: ' + id);
  return CHARACTER_WARDROBE_SOURCES[id];
}
export function getCharacterWardrobeLayers(id) {
  return { ...sourceFor(id).layers };
}
export function getCharacterWardrobeText(id, field) {
  const source = sourceFor(id);
  if (!Object.hasOwn(source.profile, field)) throw new Error('Unknown character wardrobe field: ' + id + ':' + field);
  return source.profile[field].map(part => typeof part === 'string' ? part : source.layers[part.layer]).join('');
}
